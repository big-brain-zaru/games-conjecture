"""t* = 0 is rigidity, and rigidity is what determines the extension.

`paley_exact.py` found that at p = 29 the feasibility SDP

    max t  s.t.  M(q) - t*I  psd

has t* = 0 to 1e-12.  So the extension exists but the feasible set
K = {q : M(q) psd} has EMPTY INTERIOR: every valid degree-4 extension has a
singular moment matrix.  That is not a numerical accident, it is a structure
theorem in disguise.

At t* = 0 the dual optimum Y satisfies Y psd, <Y,A_k> = 0 for all k, and
<Y,M0> = 0.  Hence for EVERY feasible q,

    <Y, M(q)> = <Y,M0> + sum_k q_k <Y,A_k> = 0,

and since Y psd and M(q) psd, this forces range(Y) contained in ker M(q).
Every valid extension is annihilated by the same subspace.  Those conditions,

    M(q) w = 0   for w in range(Y),

are LINEAR in q.  If they have a unique solution then q is not merely some point
the solver happened to reach: it is determined by linear algebra over the field
generated by the entries, which is Q(sqrt p).  That would explain everything at
once -- why the extension is exact, why it is unique, and what it is.

This script tests exactly that:
  1. take the feasible q0 found by the SDP, build M(q0);
  2. read off its numerical kernel W;
  3. ask whether the linear system M(q) W = 0 pins q down uniquely;
  4. if so, solve it and compare with q0.

Run: python paley_rigid.py [p]
"""
import json
import os
import sys

import numpy as np

from paley_exact import build_parts

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    p = int(sys.argv[1]) if len(sys.argv) > 1 else 29
    src = os.path.join(ROOT, "results", f"paley_exact_{p}.json")
    if not os.path.exists(src):
        raise SystemExit(f"missing {src} -- run paley_exact.py {p} first")
    rec = json.load(open(src, encoding="utf-8"))
    q0 = np.array(rec["q"])

    M0, A, reps, X, pairs, pidx = build_parts(p)
    n = M0.shape[0]
    K = len(reps)
    M = M0 + sum(q0[k] * A[k] for k in range(K))
    w, V = np.linalg.eigh(M)
    print(f"p = {p}: M_even is {n} x {n}, {K} Aut-orbit unknowns")
    print(f"  t* from the SDP            : {rec['t_star']:+.3e}")
    print(f"  smallest eigenvalues of M  : {', '.join(f'{x:+.2e}' for x in w[:8])}")

    for tol in (1e-6, 1e-7, 1e-8):
        r = int((np.abs(w) < tol).sum())
        print(f"  kernel dimension at tol {tol:.0e}: {r}")
    tol = 1e-7
    W = V[:, np.abs(w) < tol]
    r = W.shape[1]
    if r == 0:
        print("  no kernel found -- M is strictly definite, contradicting t* = 0")
        return
    print(f"  using kernel of dimension {r}")

    # Linear system:  sum_k q_k (A_k W) = -(M0 W),  flattened over (row, kernel vector)
    B = np.stack([(A[k] @ W).ravel() for k in range(K)], axis=1)   # (n*r, K)
    rhs = -(M0 @ W).ravel()
    rank = np.linalg.matrix_rank(B, tol=1e-8)
    print(f"\n  linear system: {B.shape[0]} equations, {K} unknowns, rank {rank}")
    sol, *_ = np.linalg.lstsq(B, rhs, rcond=None)
    resid = float(np.linalg.norm(B @ sol - rhs))
    print(f"  least-squares residual     : {resid:.3e}")
    print(f"  max |q_solved - q_SDP|     : {float(np.abs(sol - q0).max()):.3e}")

    print()
    if rank == K and resid < 1e-6:
        print("VERDICT: the kernel conditions determine q UNIQUELY.")
        print("The degree-4 extension is RIGID: there is exactly one valid q.")
        print("Caveat, stated precisely: uniqueness alone does NOT prove q lies in")
        print("Q(sqrt p). K is cut out by polynomial INEQUALITIES over Q(sqrt p), and a")
        print("field automorphism need not preserve them, so uniqueness gives only that q")
        print("is algebraic over Q(sqrt p), of unknown degree. To get q in Q(sqrt p) one")
        print("needs the kernel W itself over Q(sqrt p); the dual Y at t* = 0 supplies it,")
        print("since range(Y) is contained in ker M(q) for every feasible q. Finding that")
        print("Y exactly is the remaining step.")
    elif rank < K:
        print(f"VERDICT: the kernel conditions leave a {K - rank}-dimensional family of q.")
        print("The extension is NOT unique, so no single q is canonical. Identification")
        print("must target the whole face, or a canonically chosen point inside it.")
    else:
        print("VERDICT: system inconsistent at this tolerance; kernel estimate is unreliable.")

    out = dict(p=p, n=n, n_orbits=K, t_star=rec["t_star"],
               kernel_dim=int(r), rank=int(rank), residual=resid,
               max_dev_from_sdp=float(np.abs(sol - q0).max()),
               eigenvalues_small=[float(x) for x in w[:12]],
               q_solved=[float(v) for v in sol])
    dst = os.path.join(ROOT, "results", f"paley_rigid_{p}.json")
    with open(dst, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=1)
    print(f"\nwrote {dst}")


if __name__ == "__main__":
    main()
